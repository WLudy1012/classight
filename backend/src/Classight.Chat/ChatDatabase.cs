using Microsoft.EntityFrameworkCore;

namespace Classight.Chat;

public sealed class ChatMessage
{
    public long Id { get; set; }
    public Guid ClientId { get; set; }
    public Guid SenderId { get; set; }
    public string SenderName { get; set; } = "";
    public string Body { get; set; } = "";
    public long SentAt { get; set; }
    public bool Deleted { get; set; }
}

public sealed class ChatDatabase(DbContextOptions<ChatDatabase> options) : DbContext(options)
{
    public DbSet<ChatMessage> Messages => Set<ChatMessage>();

    protected override void OnModelCreating(ModelBuilder model)
    {
        var messages = model.Entity<ChatMessage>().ToTable("classight_chat_messages");
        messages.Property(x => x.ClientId).HasConversion<string>();
        messages.Property(x => x.SenderId).HasConversion<string>();
        messages.HasIndex(x => new { x.SenderId, x.ClientId }).IsUnique();
    }

    public static string[] Schema(string? provider)
    {
        var mysql = provider == "Pomelo.EntityFrameworkCore.MySql";
        var primaryKey = provider switch
        {
            "Pomelo.EntityFrameworkCore.MySql" => "BIGINT AUTO_INCREMENT PRIMARY KEY",
            "Microsoft.EntityFrameworkCore.Sqlite" => "INTEGER PRIMARY KEY AUTOINCREMENT",
            _ => "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
        };
        var table = $"""
            CREATE TABLE IF NOT EXISTS classight_chat_messages (
                "Id" {primaryKey},
                "ClientId" VARCHAR(36) NOT NULL,
                "SenderId" VARCHAR(36) NOT NULL,
                "SenderName" VARCHAR(200) NOT NULL,
                "Body" VARCHAR(2000) NOT NULL,
                "SentAt" BIGINT NOT NULL,
                "Deleted" BOOLEAN NOT NULL,
                UNIQUE ("SenderId", "ClientId")
            )
            """;
        return [mysql ? table.Replace('"', '`') + " DEFAULT CHARSET=utf8mb4" : table];
    }
}
